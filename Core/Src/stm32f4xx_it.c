/* USART1 DMA发送完成回调：通知VOFA可以发下一帧 */
void HAL_UART_TxCpltCallback(UART_HandleTypeDef *huart)
{
    if(huart->Instance == USART1)
    {
        VOFA_TxCpltCallback();
    }
}

void HAL_ADCEx_InjectedConvCpltCallback(ADC_HandleTypeDef *hadc)
{
    if(hadc->Instance == ADC1)
    {   /*计算ADC电流采样得到的三相电流Iu Iv Iw*/
        ADC_RealData_Transf(&MotorBLDC.ADCSamp);
        
        /*电流一阶低通滤波 直接赋值FOC参数*/
        MotorBLDC.FOCParm.Iu  = filter_lag(&MotorBLDC.FilterMethod.Iu_filter, MotorBLDC.ADCSamp.iu);
        MotorBLDC.FOCParm.Iv  = filter_lag(&MotorBLDC.FilterMethod.Iv_filter, MotorBLDC.ADCSamp.iv);
        MotorBLDC.FOCParm.Iw  = filter_lag(&MotorBLDC.FilterMethod.Iw_filter, MotorBLDC.ADCSamp.iw);

        /*执行状态机（含坐标变换、电流环、SVPWM与PWM输出）*/
        Motor_StateMachine_Run(&MotorBLDC);
            
            
    }
}



